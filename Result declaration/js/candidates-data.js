window.findCandidateMeta = function (name, houseCode) {
  if (!window.ALL_CONTESTING_CANDIDATES || !Array.isArray(window.ALL_CONTESTING_CANDIDATES)) return null;
  const cleanName = String(name || "").trim().toLowerCase();
  if (!cleanName) return null;
  const simplified = cleanName.replace(/[\.\s]+/g, "");

  // 1. Exact match
  let found = window.ALL_CONTESTING_CANDIDATES.find((c) => {
    const cName = String(c.fullName || "").trim().toLowerCase();
    const cSimp = cName.replace(/[\.\s]+/g, "");
    if (cName === cleanName || cSimp === simplified) {
      if (houseCode && c.houseCode && c.houseCode.toUpperCase() !== String(houseCode).toUpperCase()) return false;
      return true;
    }
    return false;
  });

  // 2. Substring match
  if (!found) {
    found = window.ALL_CONTESTING_CANDIDATES.find((c) => {
      const cName = String(c.fullName || "").trim().toLowerCase();
      const cSimp = cName.replace(/[\.\s]+/g, "");
      const match = cName.includes(cleanName) || cleanName.includes(cName) || cSimp.includes(simplified) || simplified.includes(cSimp);
      if (match) {
        if (houseCode && c.houseCode && c.houseCode.toUpperCase() !== String(houseCode).toUpperCase()) return false;
        return true;
      }
      return false;
    });
  }
  return found || null;
};

